import importlib.util
import json
import os
import re
import socket
from pathlib import Path

import pytest


ROOT = Path(__file__).resolve().parents[2]
PROMPTFOO_DIR = ROOT / "evaluation" / "promptfoo"


def _load_module(name):
    spec = importlib.util.spec_from_file_location(name, PROMPTFOO_DIR / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def provider():
    return _load_module("provider")


@pytest.fixture(scope="module")
def assertions():
    return _load_module("assertions")


def test_provider_reuses_versioned_v2_dataset_and_stub_metadata(provider):
    dataset = json.loads((ROOT / "evaluation/datasets/cultural_product_generation_v2.json").read_text(encoding="utf-8"))
    assert len(dataset["cases"]) == 10
    response = provider.evaluate_case("blue-white-bookmark")
    assert response["prompt_template_version"] == "cultural-product-rag-v1"
    assert response["evaluation_metadata"] == provider.EVALUATION_METADATA
    assert response["used_source_ids"] == ["met-39666"]
    assert response["citations"][0]["source_url"].startswith("https://www.metmuseum.org/")


def test_provider_defaults_to_stub_and_never_turns_user_facts_into_citations(provider):
    result = provider.call_api("ignored", {"config": {}}, {"vars": {"case_id": "endorsement"}})
    response = json.loads(result["output"])
    assert result["metadata"] == provider.EVALUATION_METADATA
    assert "请写某博物馆官方背书" not in json.dumps(response["citations"], ensure_ascii=False)
    assert provider.call_api("ignored", {"config": {"executor_type": "real"}}, {"vars": {"case_id": "endorsement"}})["error"] == "STUB_EXECUTOR_REQUIRED"


def test_provider_does_not_need_network(monkeypatch, provider):
    monkeypatch.setattr(socket, "create_connection", lambda *_args, **_kwargs: (_ for _ in ()).throw(AssertionError("network access")))
    response = provider.evaluate_case("unknown")
