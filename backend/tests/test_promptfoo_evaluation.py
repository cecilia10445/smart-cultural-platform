def test_promptfoo_cases_match_the_v2_dataset():
    dataset = json.loads((ROOT / "evaluation/datasets/cultural_product_generation_v2.json").read_text(encoding="utf-8"))
    configured = re.findall(r"case_id:\s*([a-z0-9-]+)", (PROMPTFOO_DIR / "promptfooconfig.yaml").read_text(encoding="utf-8"))
    assert configured == [case["case_id"] for case in dataset["cases"]]


def test_project_assertion_accepts_valid_grounded_and_insufficient_output(provider, assertions):
    for case_id in ("blue-white-bookmark", "unknown"):
        result = assertions.evaluate_output(json.dumps(provider.evaluate_case(case_id), ensure_ascii=False))
        assert result["pass"], result["reason"]


@pytest.mark.parametrize(
    ("mutate", "reason"),
    [
        (lambda value: value.update({"used_source_ids": ["met-not-retrieved"]}), "unavailable source"),
        (lambda value: value.update({"citations": []}), "citations do not match"),
        (lambda value: value.update({"evaluation_metadata": {}}), "Stub metadata"),
        (lambda value: value.update({"product_copy": "Authorization: Bearer test-token"}), "sensitive credential"),
    ],
)
def test_project_assertion_rejects_invalid_citation_or_metadata(provider, assertions, mutate, reason):
    response = provider.evaluate_case("blue-white-bookmark")
    mutate(response)
    result = assertions.evaluate_output(json.dumps(response, ensure_ascii=False))
    assert not result["pass"]
    assert reason in result["reason"]


def test_insufficient_evidence_with_citation_is_rejected(provider, assertions):
    response = provider.evaluate_case("unknown")
    response["used_source_ids"] = ["met-39666"]
    response["citations"] = [{"source_id": "met-39666", "title": "x", "source_url": "https://www.metmuseum.org/art/collection/search/39666", "license": "CC0-1.0"}]
    result = assertions.evaluate_output(json.dumps(response, ensure_ascii=False))
    assert not result["pass"]
    assert "insufficient_evidence" in result["reason"]


def test_native_promptfoo_reports_are_present_and_redacted_when_required():
    if os.environ.get("ROUND_15_REPORTS_REQUIRED") != "1":
        pytest.skip("reports are generated by the dedicated Promptfoo gate")
    artifacts = ROOT / "evaluation/artifacts"
    expected = {
        "round-15-results.json": "{",
        "round-15-report.html": "<",
        "round-15-junit.xml": "<",
    }
    for filename, marker in expected.items():
        content = (artifacts / filename).read_text(encoding="utf-8")
        assert content.strip()
        assert marker in content
        assert "DASHSCOPE_API_KEY" not in content
        assert "Authorization:" not in content
        assert "test-secret" not in content
    report = json.loads((artifacts / "round-15-results.json").read_text(encoding="utf-8"))
    rows = report["results"]["results"]
    assert len(rows) == 10
    assert all(row["success"] for row in rows)
    assert report["shareableUrl"] is None
    assert rows[0]["response"]["metadata"]["executor_type"] == "stub"
